const $ = id => document.getElementById(id);
const startScreen=$("startScreen"), quizScreen=$("quizScreen"), resultScreen=$("resultScreen");
const letters=["A","B","C","D"];
let vi=0, qi=0, score=0, locked=false, student="Оқушы";

function show(el){
  [startScreen,quizScreen,resultScreen].forEach(x=>x.classList.add("hidden"));
  el.classList.remove("hidden");
}

function start(){
  student=$("studentName").value.trim()||"Оқушы";
  vi=Number($("variantSelect").value); qi=0; score=0; locked=false;
  $("variantLabel").textContent=`${vi+1}-нұсқа`;
  $("studentLabel").textContent=student;
  $("liveScore").textContent=0;
  show(quizScreen); render();
}

function render(){
  locked=false;
  $("feedback").className="feedback hidden";
  $("nextBtn").classList.add("hidden");
  const [topic,q,answers,correct,exp]=V[vi][qi];
  $("questionCounter").textContent=`${qi+1} / 10`;
  $("topicTag").textContent=topic;
  $("progressBar").style.width=`${(qi+1)*10}%`;
  $("questionArea").innerHTML=`
    <div class="qnum">${qi+1}-сұрақ</div>
    <h2 class="qtitle">${q}</h2>
    <div class="answers">
      ${answers.map((x,i)=>`<button class="answer" data-i="${i}">
        <span class="letter">${letters[i]}</span><span>${x}</span>
      </button>`).join("")}
    </div>`;
  document.querySelectorAll(".answer").forEach(b=>b.onclick=()=>answer(Number(b.dataset.i)));
}

function answer(sel){
  if(locked)return;
  locked=true;
  const [topic,q,answers,correct,exp]=V[vi][qi];
  const btns=[...document.querySelectorAll(".answer")];
  btns.forEach((b,i)=>{b.disabled=true;if(i===correct)b.classList.add("correct")});
  if(sel===correct){
    score++; $("liveScore").textContent=score;
    btns[sel].classList.add("correct");
    $("feedback").className="feedback good";
    $("feedbackEmoji").textContent=["😊","🎉","🌟","👏","🤩"][Math.floor(Math.random()*5)];
    $("feedbackTitle").textContent="Дұрыс жауап!";
  }else{
    btns[sel].classList.add("wrong");
    $("feedback").className="feedback bad";
    $("feedbackEmoji").textContent=["🤔","🙂","💡","🧐"][Math.floor(Math.random()*4)];
    $("feedbackTitle").textContent="Қате жауап. Үйренуді жалғастырайық!";
  }
  $("feedbackText").textContent=exp;
  $("nextBtn").textContent=qi===9?"Нәтижені көру 🏁":"Келесі сұрақ →";
  $("nextBtn").classList.remove("hidden");
}

function next(){
  if(!locked)return;
  if(qi<9){qi++;render()}else result();
}

function result(){
  show(resultScreen);
  const p=score*10;
  $("finalScore").textContent=score;
  $("finalPercent").textContent=`${p}%`;
  $("correctCount").textContent=score;
  $("wrongCount").textContent=10-score;
  $("variantResult").textContent=vi+1;

  let emo,title,msg;
  if(score>=9){
    emo="🏆";title="Өте жақсы!";
    msg="Тақырыптарды өте жақсы меңгердіңіз. Біліміңіз жоғары деңгейде.";
  }else if(score>=7){
    emo="🌟";title="Жақсы нәтиже!";
    msg="Негізгі ұғымдарды жақсы білесіз. Қате кеткен сұрақтарды қайта қарап шығыңыз.";
  }else if(score>=5){
    emo="🙂";title="Жақсы талпыныс!";
    msg="Негізгі білім бар. ЖИ деректері, жады және файлдық жүйе тақырыптарын тағы бір қайталау пайдалы.";
  }else{
    emo="📚";title="Қайта дайындалып көрейік!";
    msg="Оқу мақсаттарын қайта қарап, түсіндірмелерді қайталаңыз. Келесі әрекетте нәтижеңіз жақсарады.";
  }
  $("resultEmoji").textContent=emo;
  $("resultTitle").textContent=title;
  $("resultSubtitle").textContent=`${student}, сіз ${vi+1}-нұсқаны аяқтадыңыз.`;
  $("resultMessage").textContent=msg;
}

$("startBtn").onclick=start;
$("nextBtn").onclick=next;
$("retryBtn").onclick=()=>{qi=0;score=0;$("liveScore").textContent=0;show(quizScreen);render()};
$("homeBtn").onclick=()=>show(startScreen);
